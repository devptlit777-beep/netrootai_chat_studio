function mergeTranslations(translated, existing) {
  if (!existing || typeof existing !== 'object' || Array.isArray(existing)) return translated;

  const merged = { ...translated };
  for (const [key, value] of Object.entries(existing)) {
    const translatedValue = translated?.[key];
    merged[key] = value && typeof value === 'object' && !Array.isArray(value)
      ? mergeTranslations(translatedValue ?? {}, value)
      : value;
  }
  return merged;
}

const loadedLanguages = new Set();

async function loadLanguageCatalog(language) {
  const loadCatalog = localeLoaders[language];
  if (!loadCatalog || loadedLanguages.has(language)) return;

  const catalog = await loadCatalog();
  const translation = mergeTranslations(
    catalog.default.translation,
    resources[language]?.translation,
  );
  resources[language] = { translation };

  if (i18n.isInitialized) {
    i18n.addResourceBundle(language, 'translation', translation, true, true);
  }

  loadedLanguages.add(language);
}

i18n.use(initReactI18next).init({
  resources,
  lng: 'en',
  fallbackLng: 'en',
  interpolation: {
    escapeValue: false,
  },
});

document.documentElement.lang = 'en';
document.documentElement.dir = 'ltr';
i18n.on('languageChanged', language => {
  document.documentElement.lang = language;
  document.documentElement.dir = ['ar', 'ur'].includes(language) ? 'rtl' : 'ltr';
  localStorage.setItem('language', language);
});

export const i18nReady = initialLanguage === 'en'
  ? Promise.resolve()
  : loadLanguageCatalog(initialLanguage).then(() => i18n.changeLanguage(initialLanguage));

export async function changeAppLanguage(language) {
  if (!supportedLanguages.includes(language)) {
    throw new Error(`Unsupported language: ${language}`);
  }

  await i18nReady;
  await loadLanguageCatalog(language);
  await i18n.changeLanguage(language);
}

